//! Incremental regeneration of the 16 m mesh blocks.

use std::collections::{BTreeMap, BTreeSet};

use faset_core::glam::Vec3;
use faset_mapfmt::geometry::{build_meshes, MeshChunk, BLOCK_SIZE_M};
use faset_mapfmt::{expand, MapFile, Symmetry, GRID_UNIT_M};

use crate::element::brush_aabb;
use crate::math::Aabb;

/// Index of a 16 m block.
pub type Block = [i32; 3];

/// The mesh chunks of the document, regenerated block by block.
///
/// Edits mark regions dirty ([`MeshCache::mark_dirty`]); [`MeshCache::rebuild`]
/// regenerates only the dirty blocks. A block is built from the brushes whose
/// bounds, grown by one grid unit, overlap it: that is every brush that can
/// cut or touch a face of the block, so the result is identical to a full
/// build.
///
/// Decision: ambient occlusion is not baked here (the preview shows flat
/// shaded chunks); a map with symmetry or prefabs rebuilds every block, since
/// one edit then also changes mirrored or repeated geometry.
#[derive(Debug, Default)]
pub struct MeshCache {
    chunks: BTreeMap<Block, MeshChunk>,
    dirty: BTreeSet<Block>,
    all_dirty: bool,
    rebuilt_total: usize,
    last_rebuilt: Vec<Block>,
}

impl MeshCache {
    /// A cache that builds everything on the first [`MeshCache::rebuild`].
    #[must_use]
    pub fn new() -> Self {
        Self {
            all_dirty: true,
            ..Self::default()
        }
    }

    /// Marks every block overlapping `region` (grown by one grid unit) dirty.
    pub fn mark_dirty(&mut self, region: &Aabb) {
        let r = region.inflated(GRID_UNIT_M);
        let (lo, hi) = (block_of(r.min), block_of(r.max));
        for x in lo[0]..=hi[0] {
            for y in lo[1]..=hi[1] {
                for z in lo[2]..=hi[2] {
                    self.dirty.insert([x, y, z]);
                }
            }
        }
    }

    /// Marks every block dirty (after loading another map).
    pub fn mark_all_dirty(&mut self) {
        self.all_dirty = true;
    }

    /// Whether a rebuild has work to do.
    #[must_use]
    pub fn is_dirty(&self) -> bool {
        self.all_dirty || !self.dirty.is_empty()
    }

    /// Regenerates the dirty blocks of `map` and returns the blocks that were
    /// regenerated.
    pub fn rebuild(&mut self, map: &MapFile) -> Vec<Block> {
        let full = self.all_dirty || map.symmetry != Symmetry::None || !map.prefabs.is_empty();
        let blocks: Vec<Block> = if full {
            let mut all: BTreeSet<Block> = self.chunks.keys().copied().collect();
            all.extend(self.dirty.iter().copied());
            self.chunks.clear();
            for chunk in build_meshes(&expand(map)) {
                all.insert(chunk.block);
                self.chunks.insert(chunk.block, chunk);
            }
            all.into_iter().collect()
        } else {
            let blocks: Vec<Block> = self.dirty.iter().copied().collect();
            for &block in &blocks {
                match build_block(map, block) {
                    Some(chunk) => {
                        self.chunks.insert(block, chunk);
                    }
                    None => {
                        self.chunks.remove(&block);
                    }
                }
            }
            blocks
        };
        self.all_dirty = false;
        self.dirty.clear();
        self.rebuilt_total += blocks.len();
        self.last_rebuilt.clone_from(&blocks);
        blocks
    }

    /// The up-to-date chunks, ordered by block index.
    pub fn chunks(&self) -> impl Iterator<Item = &MeshChunk> {
        self.chunks.values()
    }

    /// Test hook: blocks regenerated by the last [`MeshCache::rebuild`].
    #[must_use]
    pub fn last_rebuilt(&self) -> &[Block] {
        &self.last_rebuilt
    }

    /// Test hook: blocks regenerated since the cache was created.
    #[must_use]
    pub fn rebuilt_total(&self) -> usize {
        self.rebuilt_total
    }
}

#[allow(clippy::cast_possible_truncation)]
fn block_of(p: Vec3) -> Block {
    [0, 1, 2].map(|i| (p[i] / BLOCK_SIZE_M).floor() as i32)
}

/// The chunk of one block, built from the brushes that can reach it.
#[allow(clippy::cast_precision_loss)]
fn build_block(map: &MapFile, block: Block) -> Option<MeshChunk> {
    let lo = Vec3::new(block[0] as f32, block[1] as f32, block[2] as f32) * BLOCK_SIZE_M;
    let region = Aabb {
        min: lo,
        max: lo + Vec3::splat(BLOCK_SIZE_M),
    }
    .inflated(GRID_UNIT_M);
    let sub = MapFile {
        format_version: map.format_version,
        meta: map.meta.clone(),
        theme: map.theme.clone(),
        physics: None,
        symmetry: Symmetry::None,
        prefabs: Vec::new(),
        brushes: map
            .brushes
            .iter()
            .filter(|b| brush_aabb(b).intersects(&region))
            .cloned()
            .collect(),
        props: Vec::new(),
        spawns: Vec::new(),
        pickups: Vec::new(),
        zones: Vec::new(),
        lights: Vec::new(),
        // The terrain is cheap to build whole; only its triangles of this
        // block are kept.
        terrain: map.terrain.clone(),
    };
    build_meshes(&sub).into_iter().find(|c| c.block == block)
}
