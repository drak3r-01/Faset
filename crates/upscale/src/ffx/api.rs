//! The entry points of the FidelityFX API, behind a trait so detection and
//! fallback can be tested with a mock library.

use std::ffi::c_void;
use std::fmt;
use std::path::Path;
use std::sync::Arc;

use super::bindings as ffx;

/// A non-zero return code of the FidelityFX API.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct ReturnCode(pub u32);

impl fmt::Display for ReturnCode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let name = match self.0 {
            ffx::FFX_API_RETURN_OK => "ok",
            ffx::FFX_API_RETURN_ERROR => "error",
            ffx::FFX_API_RETURN_ERROR_UNKNOWN_DESCTYPE => "unknown descriptor type",
            ffx::FFX_API_RETURN_ERROR_RUNTIME_ERROR => "runtime error",
            ffx::FFX_API_RETURN_NO_PROVIDER => "no provider",
            ffx::FFX_API_RETURN_ERROR_MEMORY => "out of memory",
            ffx::FFX_API_RETURN_ERROR_PARAMETER => "invalid parameter",
            _ => "unknown error",
        };
        write!(f, "{name} (code {})", self.0)
    }
}

/// Turns a raw return code into a result.
pub(crate) fn check(code: u32) -> Result<(), ReturnCode> {
    if code == ffx::FFX_API_RETURN_OK {
        Ok(())
    } else {
        Err(ReturnCode(code))
    }
}

/// The functions of `ffx_api.h` used here. The memory callbacks are always
/// null (the library's own allocator).
///
/// # Safety
/// Every method forwards raw pointers to the library: the descriptor chains
/// must be valid as `ffx_api.h` describes, and the Vulkan handles inside
/// them live.
pub(crate) trait FfxApi {
    unsafe fn create_context(
        &self,
        context: &mut ffx::ffxContext,
        desc: *mut ffx::ffxApiHeader,
    ) -> u32;
    unsafe fn destroy_context(&self, context: &mut ffx::ffxContext) -> u32;
    unsafe fn query(&self, context: &mut ffx::ffxContext, desc: *mut ffx::ffxApiHeader) -> u32;
    unsafe fn dispatch(&self, context: &mut ffx::ffxContext, desc: *const ffx::ffxApiHeader)
        -> u32;
}

impl FfxApi for ffx::FfxLibrary {
    unsafe fn create_context(
        &self,
        context: &mut ffx::ffxContext,
        desc: *mut ffx::ffxApiHeader,
    ) -> u32 {
        // SAFETY: forwarded from the caller.
        unsafe { self.ffxCreateContext(context, desc, std::ptr::null()) }
    }

    unsafe fn destroy_context(&self, context: &mut ffx::ffxContext) -> u32 {
        // SAFETY: forwarded from the caller.
        unsafe { self.ffxDestroyContext(context, std::ptr::null()) }
    }

    unsafe fn query(&self, context: &mut ffx::ffxContext, desc: *mut ffx::ffxApiHeader) -> u32 {
        // SAFETY: forwarded from the caller.
        unsafe { self.ffxQuery(context, desc) }
    }

    unsafe fn dispatch(
        &self,
        context: &mut ffx::ffxContext,
        desc: *const ffx::ffxApiHeader,
    ) -> u32 {
        // SAFETY: forwarded from the caller.
        unsafe { self.ffxDispatch(context, desc) }
    }
}

/// Loads the library at `path` and resolves its five entry points.
pub(crate) fn load(path: &Path) -> Result<Arc<dyn FfxApi>, String> {
    // SAFETY: loading runs the library's initialisers. Only AMD's official
    // FidelityFX API library is loaded, from the executable's directory, and
    // the symbols are typed after its own header (bindings generated by
    // bindgen from `ffx_api.h`).
    match unsafe { ffx::FfxLibrary::new(path) } {
        Ok(lib) => Ok(Arc::new(lib)),
        Err(e) => Err(format!("cannot load {}: {e}", path.display())),
    }
}

/// Receives the library's messages (UTF-16, null-terminated) and logs them.
pub(crate) unsafe extern "C" fn on_message(kind: u32, message: *const u16) {
    /// Longest message read, in UTF-16 units.
    const MAX: usize = 4096;
    let text = if message.is_null() {
        String::new()
    } else {
        let mut len = 0;
        // SAFETY: the library passes a null-terminated string; reading stops
        // at the terminator or after MAX units.
        while len < MAX && unsafe { *message.add(len) } != 0 {
            len += 1;
        }
        // SAFETY: `len` units were just read.
        String::from_utf16_lossy(unsafe { std::slice::from_raw_parts(message, len) })
    };
    if kind == ffx::FFX_API_MESSAGE_TYPE_ERROR {
        tracing::error!(target: "faset_upscale::fsr3", "{text}");
    } else {
        tracing::warn!(target: "faset_upscale::fsr3", "{text}");
    }
}

/// The name of the provider (the effect version) a context runs, if the
/// library reports one.
pub(crate) fn provider_name(api: &dyn FfxApi, context: &mut ffx::ffxContext) -> Option<String> {
    let mut query = ffx::ffxQueryGetProviderVersion {
        header: ffx::ffxApiHeader {
            type_: u64::from(ffx::FFX_API_QUERY_DESC_TYPE_GET_PROVIDER_VERSION),
            pNext: std::ptr::null_mut(),
        },
        versionId: 0,
        versionName: std::ptr::null(),
    };
    // SAFETY: a live context and a valid, unchained query descriptor.
    let code = unsafe { api.query(context, &mut query.header) };
    if check(code).is_err() || query.versionName.is_null() {
        return None;
    }
    // SAFETY: the library returns a static null-terminated name.
    let name = unsafe { std::ffi::CStr::from_ptr(query.versionName) };
    Some(name.to_string_lossy().into_owned())
}

/// A Vulkan handle as the `void*` the FidelityFX API takes.
pub(crate) fn raw_handle(handle: impl ash::vk::Handle) -> *mut c_void {
    handle.as_raw() as usize as *mut c_void
}
