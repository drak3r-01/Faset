#!/usr/bin/env sh
# Regenerates crates/upscale/src/ffx/bindings.rs from the vendored headers of
# the FidelityFX API (FidelityFX SDK v1.1.4, MIT, see LICENSE.txt).
#
# Run it in Docker, never on the host:
#   docker compose run --rm dev sh crates/upscale/ffx/generate-bindings.sh
#
# The bindings are committed, so a normal build needs neither bindgen nor
# libclang. Vulkan types come from `ash`; `wchar_t` is 16 bits as on Windows
# (-fshort-wchar), the only platform where the library is loaded.
set -eu
cd "$(dirname "$0")"

if ! command -v bindgen >/dev/null 2>&1; then
    cargo install --locked bindgen-cli --version 0.72.1
fi
if [ ! -f /usr/include/vulkan/vulkan.h ]; then
    apt-get update && apt-get install -y --no-install-recommends libvulkan-dev
fi

bindgen wrapper.h -o ../src/ffx/bindings.rs \
    --rust-target 1.82 \
    --dynamic-loading FfxLibrary \
    --dynamic-link-require-all \
    --allowlist-function 'ffx(CreateContext|DestroyContext|Configure|Query|Dispatch)' \
    --allowlist-type 'ffxApiHeader|ffx(CreateContext|Configure|Query|Dispatch)DescHeader|ffxCreateContextDescUpscale|ffxDispatchDescUpscale|ffxCreateBackendVKDesc|ffxQueryGetProviderVersion|ffxAllocationCallbacks|ffxContext|ffxReturnCode_t|ffxStructType_t|ffxApiMessage|FfxApi(Resource|ResourceDescription|Dimensions2D|FloatCoords2D|ReturnCodes|SurfaceFormat|ResourceUsage|ResourceState|ResourceType|ResourceFlags|CreateContextUpscaleFlags|DispatchFsrUpscaleFlags|MsgType)' \
    --allowlist-var 'FFX_API_(CREATE_CONTEXT_DESC_TYPE_(UPSCALE|BACKEND_VK)|DISPATCH_DESC_TYPE_UPSCALE|QUERY_DESC_TYPE_GET_PROVIDER_VERSION)' \
    --blocklist-type 'Vk.*|PFN_vk.*' \
    --raw-line '// Generated by generate-bindings.sh (bindgen 0.72.1); do not edit.' \
    --raw-line 'pub type VkDevice = ash::vk::Device;' \
    --raw-line 'pub type VkPhysicalDevice = ash::vk::PhysicalDevice;' \
    --raw-line 'pub type PFN_vkGetDeviceProcAddr = Option<ash::vk::PFN_vkGetDeviceProcAddr>;' \
    --default-enum-style consts \
    --no-prepend-enum-name \
    --with-derive-default \
    --no-doc-comments \
    -- -x c++ -std=c++17 -fdeclspec -fshort-wchar -Iinclude

rustfmt --edition 2021 ../src/ffx/bindings.rs
